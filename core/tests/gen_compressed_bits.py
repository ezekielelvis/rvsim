#!/usr/bin/env python3
"""Regenerates compressed_bits.inc: one decode16 test vector per immediate bit
of every RV64C format, using the GNU assembler as the reference encoder.

    python3 core/tests/gen_compressed_bits.py > core/tests/compressed_bits.inc

Branch and jump encodings cannot be assembled with numeric offsets (the
assembler relaxes them), so they are hand-encoded and their offsets checked
by disassembling them with objdump.
"""
import os
import subprocess
import sys
import tempfile

AS = os.environ.get("RISCV_PREFIX", "riscv64-unknown-elf-") + "as"
OBJDUMP = os.environ.get("RISCV_PREFIX", "riscv64-unknown-elf-") + "objdump"


def assemble(src, tmp):
    s, o = os.path.join(tmp, "x.s"), os.path.join(tmp, "x.o")
    with open(s, "w") as f:
        f.write(".option rvc\n" + src)
    subprocess.run([AS, "-march=rv64imac", "-o", o, s], check=True)
    out = subprocess.run([OBJDUMP, "-d", o], capture_output=True, text=True, check=True).stdout
    return [l for l in out.splitlines() if ":\t" in l]


def main():
    cases = []

    def add(asm, op, rd, rs1, rs2, imm):
        cases.append((asm, op, rd, rs1, rs2, imm))

    for b in range(2, 10): add(f"c.addi4spn s0, sp, {1 << b}", "Addi", 8, 2, 0, 1 << b)
    for b in range(2, 7): add(f"c.lw a0, {1 << b}(a1)", "Lw", 10, 11, 0, 1 << b)
    for b in range(3, 8): add(f"c.ld a0, {1 << b}(a1)", "Ld", 10, 11, 0, 1 << b)
    for b in range(2, 7): add(f"c.sw a2, {1 << b}(s1)", "Sw", 0, 9, 12, 1 << b)
    for b in range(3, 8): add(f"c.sd a2, {1 << b}(s1)", "Sd", 0, 9, 12, 1 << b)
    for b in range(0, 5): add(f"c.addi a0, {1 << b}", "Addi", 10, 10, 0, 1 << b)
    for b in range(0, 5): add(f"c.addiw a0, {1 << b}", "Addiw", 10, 10, 0, 1 << b)
    for b in range(0, 5): add(f"c.li a0, {1 << b}", "Addi", 10, 0, 0, 1 << b)
    for b in range(4, 9): add(f"c.addi16sp sp, {1 << b}", "Addi", 2, 2, 0, 1 << b)
    for b in range(0, 5): add(f"c.lui a0, {1 << b}", "Lui", 10, 0, 0, (1 << b) << 12)
    for b in range(0, 6): add(f"c.srli s0, {1 << b}", "Srli", 8, 8, 0, 1 << b)
    for b in range(0, 6): add(f"c.srai s0, {1 << b}", "Srai", 8, 8, 0, 1 << b)
    for b in range(0, 5): add(f"c.andi s0, {1 << b}", "Andi", 8, 8, 0, 1 << b)
    for b in range(0, 6): add(f"c.slli a0, {1 << b}", "Slli", 10, 10, 0, 1 << b)
    for b in range(2, 8): add(f"c.lwsp a0, {1 << b}(sp)", "Lw", 10, 2, 0, 1 << b)
    for b in range(3, 9): add(f"c.ldsp a0, {1 << b}(sp)", "Ld", 10, 2, 0, 1 << b)
    for b in range(2, 8): add(f"c.swsp a0, {1 << b}(sp)", "Sw", 0, 2, 10, 1 << b)
    for b in range(3, 9): add(f"c.sdsp a0, {1 << b}(sp)", "Sd", 0, 2, 10, 1 << b)

    def cj(off):  # Unpriv §16.5 CJ format
        o = off & 0xfff
        b = lambda i: (o >> i) & 1
        return (0xa001 | b(11) << 12 | b(4) << 11 | b(9) << 10 | b(8) << 9 | b(10) << 8 |
                b(6) << 7 | b(7) << 6 | b(3) << 5 | b(2) << 4 | b(1) << 3 | b(5) << 2)

    def cb(off):  # CB format, C.BEQZ s0
        o = off & 0x1ff
        b = lambda i: (o >> i) & 1
        return (6 << 13 | 1 | b(8) << 12 | b(4) << 11 | b(3) << 10 | b(7) << 6 | b(6) << 5 |
                b(2) << 4 | b(1) << 3 | b(5) << 2)

    branches = [(cj(1 << i), "Jal", 0, 0, 0, 1 << i, f"c.j +{1 << i}") for i in range(1, 11)]
    branches += [(cb(1 << i), "Beq", 0, 8, 0, 1 << i, f"c.beqz s0, +{1 << i}") for i in range(1, 8)]

    with tempfile.TemporaryDirectory() as tmp:
        lines = assemble("\n".join(c[0] for c in cases) + "\n", tmp)
        hexes = [l.split("\t")[1].strip() for l in lines]
        assert len(hexes) == len(cases) and all(len(h) == 4 for h in hexes)
        dis = assemble("".join(f".insn 2, {h:#x}\n" for h, *_ in branches), tmp)
        for (h, *_, imm, name), d in zip(branches, dis):
            f = d.split("\t")
            addr = int(f[0].strip().rstrip(":"), 16)
            target = int(f[3].split()[0].split(",")[-1], 16)
            if target - addr != imm:
                sys.exit(f"{name}: objdump says offset {target - addr}, expected {imm}")

    print("// Generated by core/tests/gen_compressed_bits.py from the GNU assembler")
    print("// (riscv64-unknown-elf-as -march=rv64imac); do not edit by hand. Each row sets")
    print("// exactly one immediate bit, so a decoder that misplaces any bit fails.")
    print("// Branch/jump rows are hand-encoded and their offsets checked with objdump.")
    print("// {encoding, op, rd, rs1, rs2, imm}")
    for (asm, op, rd, rs1, rs2, imm), h in zip(cases, hexes):
        print(f"  {{0x{h}, Op::{op}, {rd}, {rs1}, {rs2}, {imm}}},  // {asm}")
    for h, op, rd, rs1, rs2, imm, name in branches:
        print(f"  {{0x{h:04x}, Op::{op}, {rd}, {rs1}, {rs2}, {imm}}},  // {name} (objdump-verified)")


if __name__ == "__main__":
    main()
